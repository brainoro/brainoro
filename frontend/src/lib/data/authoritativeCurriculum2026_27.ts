/**
 * Normalizes subject string for query compatibility.
 * e.g. 'SCIENCE' -> 'SCIENCE', 'CBSE-SUB-SCI' -> 'SCIENCE', 'MATH' -> 'MATH', 'CBSE-SUB-MATH' -> 'MATH'.
 */
export function normalizeAuthoritativeSubject(subject: string): string {
  const s = subject.toUpperCase();
  if (s.includes('SCI') && !s.includes('SOC')) return 'SCIENCE';
  if (s.includes('MATH')) return 'MATH';
  if (s.includes('ENG')) return 'ENGLISH';
  if (s.includes('SOC')) return 'SOCIAL_SCIENCE';
  if (s.includes('HIN')) return 'HINDI';
  if (s.includes('SANSKRIT') || s.includes('SKT')) return 'SANSKRIT';
  return s;
}

/**
 * Retrieves all registered authoritative textbooks for a grade and subject.
 */
export function getAuthoritativeTextbooks(
  grade: number,
  subject: string
): AuthoritativeTextbookRecord[] {
  const normalized = normalizeAuthoritativeSubject(subject);
  return AUTHORITATIVE_TEXTBOOKS_2026_27.filter(
    (tb) => tb.grade_level === grade && normalizeAuthoritativeSubject(tb.subject_id) === normalized
  ).sort((a, b) => a.part_number - b.part_number);
}

/**
 * Retrieves authoritative chapters for a grade and subject, optionally filtered by part.
 */
export function getAuthoritativeChapters(
  grade: number,
  subject: string,
  partNumber?: number
): AuthoritativeCurriculumMapping[] {
  const normalized = normalizeAuthoritativeSubject(subject);
  return AUTHORITATIVE_CURRICULUM_MAPPINGS_2026_27.filter((ch) => {
    if (ch.grade_level !== grade) return false;
    if (normalizeAuthoritativeSubject(ch.subject_id) !== normalized) return false;
    if (partNumber !== undefined && ch.part_number !== partNumber) return false;
    return ch.is_authoritative;
  }).sort((a, b) => {
    if (a.part_number !== b.part_number) return a.part_number - b.part_number;
    return a.chapter_no - b.chapter_no;
  });
}

/**
 * Validates package completeness against statutory requirements.
 */
export function validatePackageCompleteness(
  grade: number,
  subject: string,
  foundPartNumbers: number[]
): { isComplete: boolean; expectedParts: number[]; missingParts: number[] } {
  const normalized = normalizeAuthoritativeSubject(subject);
  const req = SUBJECT_PACKAGE_REQUIREMENTS.find(
    (r) => r.grade_level === grade && normalizeAuthoritativeSubject(r.subject_id) === normalized
  );

  const expectedParts = req ? req.required_parts : (foundPartNumbers.length > 0 ? foundPartNumbers : [1]);
  const missingParts = expectedParts.filter((p) => !foundPartNumbers.includes(p));

  return {
    isComplete: missingParts.length === 0,
    expectedParts,
    missingParts,
  };
}
