/**
 * Normalizes title string formatting (whitespace, typographic dashes, smart quotes)
 * WITHOUT normalizing away meaningful educational differences (e.g. Roman numerals,
 * hyphenated part numbers like 'Proportional Reasoning-1' vs 'Proportional Reasoning-2').
 */
export function normalizeChapterTitle(raw: string): string {
  if (!raw) return '';
  return raw
    .trim()
    .replace(/[\u2018\u2019]/g, "'")       // smart single quotes
    .replace(/[\u201C\u201D]/g, '"')       // smart double quotes
    .replace(/[\u2013\u2014]/g, '-')       // en/em dashes to standard hyphen
    .replace(/\s+/g, ' ')                  // normalize consecutive spaces
    .replace(/\s*:\s*/g, ': ')             // standardized colon spacing
    .trim();
}

