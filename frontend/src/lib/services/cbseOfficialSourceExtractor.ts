/**
 * Extracts and returns the official Table of Contents for a given manifest entry.
 * Fails closed with 'PENDING_VERIFICATION' and [] chapters if the official source
 * is unverified or unavailable.
 */
export async function extractOfficialTextbookToc(
  entry: CbseSourceManifestEntry
): Promise<OfficialExtractedTextbook> {
  // Fail-closed check
  if (entry.verification_status !== 'VERIFIED' || !entry.official_source_code || entry.official_source_code === 'UNASSIGNED') {
    return {
      textbook_id: entry.textbook_id,
      official_code: entry.official_source_code,
      official_title: entry.official_textbook_name,
      grade_level: entry.grade_level,
      subject_id: entry.subject_id,
      curriculum_version_id: entry.curriculum_version_id,
      stream_id: entry.stream_id,
      part_volume: entry.part_volume,
      chapters: [],
      source_url: entry.official_source_url,
      verification_status: 'PENDING_VERIFICATION',
    };
  }

  const rawTitles = STATUTORY_NCERT_ORACLE_TOC[entry.official_source_code];
  if (!rawTitles || rawTitles.length === 0) {
    return {
      textbook_id: entry.textbook_id,
      official_code: entry.official_source_code,
      official_title: entry.official_textbook_name,
      grade_level: entry.grade_level,
      subject_id: entry.subject_id,
      curriculum_version_id: entry.curriculum_version_id,
      stream_id: entry.stream_id,
      part_volume: entry.part_volume,
      chapters: [],
      source_url: entry.official_source_url,
      verification_status: 'PENDING_VERIFICATION',
    };
  }

  const chapters: OfficialExtractedChapter[] = rawTitles.map((title, idx) => {
    const order = idx + 1;
    return {
      chapter_number: order,
      chapter_title: normalizeChapterTitle(title),
      official_sequence_order: order,
      part_volume: entry.part_volume || null,
      description: `Official Chapter ${order}: ${normalizeChapterTitle(title)} from ${entry.official_textbook_name}`,
      sections_available: true,
    };
  });

  return {
    textbook_id: entry.textbook_id,
    official_code: entry.official_source_code,
    official_title: entry.official_textbook_name,
    grade_level: entry.grade_level,
    subject_id: entry.subject_id,
    curriculum_version_id: entry.curriculum_version_id,
    stream_id: entry.stream_id,
    part_volume: entry.part_volume,
    chapters,
    source_url: entry.official_source_url,
    verification_status: 'VERIFIED',
  };
}
